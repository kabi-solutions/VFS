let mockSessionUserId = "user-borrower-1";

function readStoredSessionUserId(): string | null {
  if (typeof window === "undefined") return null;
  try {
    return localStorage.getItem(SESSION_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function getSession(): SessionUser {
  const stored = readStoredSessionUserId();
  if (stored) mockSessionUserId = stored;
  const user = users.find((u) => u.id === mockSessionUserId) ?? users[0];
  const organization =
    organizations.find((o) => o.id === user.organization_id) ?? null;
  return { user, organization };
}

export function setMockSessionUserId(userId: string) {
  mockSessionUserId = userId;
  if (typeof window !== "undefined") {
    try {
      localStorage.setItem(SESSION_STORAGE_KEY, userId);
    } catch {
      /* ignore quota / private mode */
    }
  }
}

export function clearMockSession() {
  mockSessionUserId = "user-borrower-1";
  if (typeof window !== "undefined") {
    try {
      localStorage.removeItem(SESSION_STORAGE_KEY);
    } catch {
      /* ignore */
    }
  }
}
